// Builds the placeholder pages (privacy, terms, cookies) and 404.html from index.html's header and footer,
// so every page shares the same navigation. Re-run after editing the header or footer in index.html:
//   node scripts/build-pages.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const index = readFileSync('public/index.html', 'utf8');
const slice = (start, end) => index.slice(index.indexOf(start), index.indexOf(end) + end.length);

// On sub-pages, in-page anchors point back to the home page and CTA focus hints are dropped.
const crossPage = (html) => html
  .replace(/href="#home"/g, 'href="/"')
  .replace(/href="#([a-z0-9-]+)"/g, 'href="/#$1"')
  .replace(/ data-focus="[^"]*"/g, '');

const header = crossPage(slice('<header class="site-header', '</header>'));
const footer = crossPage(slice('<footer class="site-footer', '</footer>'));

const PAGES = [
  { file: 'privacy.html', title: 'Privacy Policy', description: 'Privacy Policy of MTI AI SOLUTIONS.' },
  { file: 'terms.html', title: 'Terms & Conditions', description: 'Terms & Conditions of MTI AI SOLUTIONS.' },
  { file: 'cookies.html', title: 'Cookie Policy', description: 'Cookie Policy of MTI AI SOLUTIONS.' },
  { file: '404.html', title: 'Page not found', description: 'The page you requested could not be found.', notFound: true },
];

const esc = (s) => s.replace(/&/g, '&amp;');

for (const page of PAGES) {
  const body = page.notFound
    ? `        <p class="eyebrow">Error 404</p>
        <h1>Page not found</h1>
        <p>The page you are looking for does not exist or has moved.</p>
        <a class="btn btn-primary" href="/">Back to Home</a>`
    : `        <p class="eyebrow">Legal</p>
        <h1>${esc(page.title)}</h1>
        <p class="placeholder-note">
          <svg class="icon" aria-hidden="true" focusable="false"><use href="/assets/img/icons.svg#info"/></svg>
          <span>This page is to be completed by MTI AI SOLUTIONS.</span>
        </p>
        <p>For any questions in the meantime, please contact us at <a href="mailto:info@mtiaisolutions.com">info@mtiaisolutions.com</a>.</p>
        <a class="btn btn-primary" href="/">Back to Home</a>`;

  const html = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <script>document.documentElement.classList.add('js')</script>
  <title>${esc(page.title)} — MTI AI SOLUTIONS</title>
  <meta name="description" content="${esc(page.description)}">
  <meta name="robots" content="noindex, follow">
  <meta name="theme-color" content="#0D1B3E">
  <link rel="icon" href="/assets/icons/favicon.ico" sizes="48x48">
  <link rel="icon" href="/assets/icons/favicon.svg" type="image/svg+xml">
  <link rel="apple-touch-icon" href="/assets/icons/app-icon-180.png">
  <link rel="manifest" href="/site.webmanifest">
  <link rel="preload" href="/assets/fonts/inter-latin-var.woff2" as="font" type="font/woff2" crossorigin>
  <link rel="stylesheet" href="/assets/css/main.css">
  <script type="module" src="/assets/js/main.js"></script>
</head>
<body>
  <!-- Generated by scripts/build-pages.mjs from index.html. Edit the header/footer there. -->
  <a class="skip-link" href="#main">Skip to main content</a>

  ${header}

  <main id="main" class="page-plain">
    <div class="container narrow">
${body}
    </div>
  </main>

  ${footer}
</body>
</html>
`;
  writeFileSync(`public/${page.file}`, html);
  console.log(`public/${page.file}`);
}
